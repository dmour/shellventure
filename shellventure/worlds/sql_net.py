"""SQL Vault (postgres in a local docker container) and Network Maze (kind cluster + local cert files)."""
import base64, gzip, json, random, shutil, subprocess, time

PG = "postgres:16-alpine"
PGC = "shellventure-pg"


def make(api):
    kc = api.kc

    # ================================================================ SQL
    def psql(sql, db="shop", check=True, env=None):
        cmd = ["docker", "exec"]
        for k, v in (env or {}).items():
            cmd += ["-e", f"{k}={v}"]
        r = subprocess.run(cmd + [PGC, "psql", "-v", "ON_ERROR_STOP=1", "-tA", "-U", "postgres", "-d", db, "-c", sql],
                           capture_output=True, text=True)
        if check and r.returncode != 0:
            raise RuntimeError(f"psql: {sql[:80]}\n{r.stderr}")
        return r

    def start_blocker():
        subprocess.run(["docker", "exec", "-d", "-e", "PGAPPNAME=batch-job-17", PGC, "psql", "-U", "postgres", "-d", "shop", "-c",
                        "BEGIN; LOCK TABLE accounts IN ACCESS EXCLUSIVE MODE; SELECT pg_sleep(86400);"], check=True)

    def sql_setup(d, w):
        api.sh(f"docker image inspect {PG} >/dev/null 2>&1 || docker pull -q {PG}")
        api.sh(["docker", "rm", "-f", PGC], check=False)
        api.sh(["docker", "run", "-d", "--name", PGC, "-e", "POSTGRES_PASSWORD=escape", PG])
        for _ in range(60):
            if psql("select 1", db="postgres", check=False).returncode == 0:
                break
            time.sleep(1)
        time.sleep(2)
        psql("CREATE DATABASE shop", db="postgres")
        rnd = random.Random()
        # 1. duplicate tenant
        names = sorted({f"{rnd.choice(api.WORDS)}-{rnd.choice(['shop', 'cloud', 'labs', 'works'])}-{rnd.randint(1, 999)}"
                        for _ in range(260)})[:200]
        dup = rnd.choice(names)
        rows = names + [dup]
        rnd.shuffle(rows)
        psql("CREATE TABLE tenants (id serial PRIMARY KEY, name text, created date);"
             "INSERT INTO tenants (name, created) VALUES " +
             ",".join(f"('{n}', DATE '2026-01-01' + {rnd.randint(0, 300)})" for n in rows))
        w["answers"]["1"] = api.h(dup)
        # 2. slow query (no index on ref)
        psql("CREATE TABLE payments (id bigserial PRIMARY KEY, ref text, customer_id int, amount numeric(12,2), status text, created_at timestamptz);"
             "INSERT INTO payments (ref, customer_id, amount, status, created_at) "
             "SELECT 'PAY' || lpad(g::text, 9, '0'), 1 + (g % 40), round((random()*900+10)::numeric, 2), "
             "(ARRAY['OK','OK','OK','FAILED','PENDING'])[1 + (g % 5)], TIMESTAMPTZ '2026-09-01' + (g % 70) * INTERVAL '1 day' "
             "FROM generate_series(1, 300000) g; ANALYZE payments;")
        # 3. lock hunt
        psql("CREATE TABLE accounts (id int PRIMARY KEY, owner text, balance numeric);"
             "INSERT INTO accounts SELECT g, 'owner-' || g, 1000 FROM generate_series(1, 50) g;")
        start_blocker()
        # 4. join riddle: who has the biggest FAILED total in October 2026
        custs = rnd.sample([f"{a}-{b}" for a in api.NAMES for b in api.WORDS], 40)
        psql("CREATE TABLE customers (id int PRIMARY KEY, name text);"
             "INSERT INTO customers VALUES " + ",".join(f"({i + 1}, '{n}')" for i, n in enumerate(custs)))
        win = rnd.randint(1, 40)
        psql(f"INSERT INTO payments (ref, customer_id, amount, status, created_at) VALUES "
             f"('PAYX1', {win}, 600000, 'FAILED', '2026-10-12'),"
             f"('PAYX2', {win % 40 + 1}, 900000, 'FAILED', '2026-09-28'),"   # trap: wrong month
             f"('PAYX3', {(win + 1) % 40 + 1}, 800000, 'OK', '2026-10-03')")  # trap: not failed
        top = psql("SELECT c.name FROM payments p JOIN customers c ON c.id = p.customer_id "
                   "WHERE p.status = 'FAILED' AND p.created_at >= '2026-10-01' AND p.created_at < '2026-11-01' "
                   "GROUP BY c.name ORDER BY sum(p.amount) DESC LIMIT 1").stdout.strip()
        w["answers"]["4"] = api.h(top)
        # 5. identity sequence behind the data (after an import)
        psql("CREATE TABLE invoices (id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, amount numeric);"
             "INSERT INTO invoices (id, amount) SELECT g, 10 FROM generate_series(1, 500) g;")
        (d / "README.txt").parent.mkdir(parents=True, exist_ok=True)
        (d / "README.txt").write_text("Connect: docker exec -it shellventure-pg psql -U postgres -d shop\n")

    def q_index(d, w, _):
        plan = psql("EXPLAIN SELECT * FROM payments WHERE ref = 'PAY000123456'", check=False).stdout
        if "Index" not in plan:
            return False, "The plan is still:\n" + plan.strip().splitlines()[0]
        n = psql("SELECT count(*) FROM payments", check=False).stdout.strip()
        return n == "300003", "No cheating: keep all payments."

    def q_lock(d, w, _):
        cnt = psql("SET lock_timeout = '2s'; SELECT count(*) FROM accounts", check=False)
        if cnt.returncode == 0 and cnt.stdout.strip().splitlines()[-1] != "50":
            return False, "No cheating: keep the accounts table and its 50 rows."
        r = psql("SET lock_timeout = '2s'; BEGIN; UPDATE accounts SET balance = balance + 1 WHERE id = 1; ROLLBACK;", check=False)
        if r.returncode != 0:
            return False, "The UPDATE still waits: " + (r.stderr.strip().splitlines() or ["lock timeout"])[-1]
        return True, ""

    def q_seq(d, w, _):
        r = psql("BEGIN; INSERT INTO invoices (amount) VALUES (1); ROLLBACK;", check=False)
        if r.returncode != 0:
            return False, (r.stderr.strip().splitlines() or ["insert failed"])[0]
        n = int(psql("SELECT count(*) FROM invoices", check=False).stdout.strip() or 0)
        return n == 500, "No cheating: keep the 500 imported invoices."

    SQL = {"title": "SQL Vault", "needs": ["docker"], "dir": "sql", "setup": sql_setup, "rooms": [
        {"name": "The Twin Tenant", "answer": True,
         "story": "Duplicate key error again. One tenant name exists [bold]twice[/] in tenants.",
         "task": "Connect: [bold]docker exec -it shellventure-pg psql -U postgres -d shop[/]\nFind the duplicated name. Then: [cyan]check <name>[/]",
         "hints": ["GROUP BY the name and count.", "`SELECT name, count(*) FROM tenants GROUP BY name HAVING count(*) > 1;`",
                   "That query is the full answer."]},
        {"name": "The Slow Query", "check": q_index,
         "story": "`SELECT * FROM payments WHERE ref = '...'` reads all 300,000 rows. Every time.",
         "task": "Make that query use an [bold]index[/] (check with EXPLAIN). Keep all rows.\nThen: [cyan]check[/]",
         "hints": ["`EXPLAIN SELECT * FROM payments WHERE ref = 'PAY000123456';`  Seq Scan = reads everything.",
                   "Which column is in the WHERE?", "`CREATE INDEX ON payments (ref);`"]},
        {"name": "The Lock Hunt", "check": q_lock,
         "story": "`UPDATE accounts SET balance = balance + 1 WHERE id = 1;` hangs forever. Someone holds a lock.",
         "task": "Find the session that blocks [bold]accounts[/] and stop it. Keep the table.\nThen: [cyan]check[/]",
         "hints": ["`SELECT pid, application_name, state, query FROM pg_stat_activity WHERE datname = 'shop';`",
                   "Look for 'idle in transaction' or a long pg_sleep. `pg_blocking_pids(pid)` also helps.",
                   "`SELECT pg_terminate_backend(pid) FROM pg_stat_activity WHERE application_name = 'batch-job-17';`"]},
        {"name": "The Join Riddle", "answer": True,
         "story": "Finance asks: who lost the most money in [bold]October 2026[/]?",
         "task": "Which customer [bold]name[/] has the highest total amount of [bold]FAILED[/] payments\n"
                 "created in October 2026? Then: [cyan]check <name>[/]",
         "hints": ["JOIN payments to customers on customer_id.",
                   "Filter: status = 'FAILED' AND created_at >= '2026-10-01' AND created_at < '2026-11-01'.",
                   "`... GROUP BY c.name ORDER BY sum(p.amount) DESC LIMIT 1;`"]},
        {"name": "The Stuck Sequence", "check": q_seq,
         "story": "500 invoices were imported with their ids. Now every new invoice fails.",
         "task": "Make `INSERT INTO invoices (amount) VALUES (1);` work. Keep the 500 rows.\nThen: [cyan]check[/]",
         "hints": ["Read the error: which constraint, which id?",
                   "The identity sequence still starts at 1. `SELECT pg_get_serial_sequence('invoices', 'id');`",
                   "`SELECT setval(pg_get_serial_sequence('invoices','id'), (SELECT max(id) FROM invoices));`"]},
    ]}

    # ================================================================ NETWORK
    def ossl(*args, cwd):
        subprocess.run(["openssl", *args], cwd=cwd, check=True, capture_output=True)

    def net_setup(d, w):
        with api.con.status("[cyan]Building Network Maze (kind, about 1 minute)...", spinner="dots12"):
            api.kind_up()
            if d.exists():
                shutil.rmtree(d)
            for ns in ("net1", "secrets", "net4", "net5"):
                kc("delete", "ns", ns, "--ignore-not-found", "--wait=true")
                kc("create", "ns", ns)
            items = [
                api.deploy("net1", "client", {"image": "busybox:1.36", "command": ["sleep", "infinity"]}),
                api.deploy("secrets", "vault", {"image": "nginx:1.27-alpine"}),
                {"apiVersion": "v1", "kind": "Service", "metadata": {"name": "vault", "namespace": "secrets"},
                 "spec": {"selector": {"app": "vault"}, "ports": [{"port": 80}]}}]
            # 4. radio: unknown port, no Service, code gzipped in a configmap
            real4, port = api.code(), random.randint(7000, 7999)
            items.append({"apiVersion": "v1", "kind": "ConfigMap", "metadata": {"name": "radio-www", "namespace": "net4"},
                          "binaryData": {"index.html.gz": base64.b64encode(gzip.compress(f"code: {real4}\n".encode())).decode()}})
            radio = api.deploy("net4", "radio", {"image": "busybox:1.36",
                                                 "command": ["sh", "-c", f"mkdir -p /www && gunzip -c /cfg/index.html.gz > /www/index.html && httpd -f -p {port} -h /www"],
                                                 "volumeMounts": [{"name": "cfg", "mountPath": "/cfg"}]})
            radio["spec"]["template"]["spec"]["volumes"] = [{"name": "cfg", "configMap": {"name": "radio-www"}}]
            items.append(radio)
            w["answers"]["4"] = api.h(real4)
            # 5. host header: the code only comes back for the right Host
            real5 = api.code()
            conf = ("server { listen 80 default_server; return 404 'wrong door\\n'; }\n"
                    "server { listen 80; server_name vault.shellventure.local; "
                    f"add_header X-Escape-Code {real5} always; return 200 'welcome. the code is in a header\\n'; }}\n")
            items.append({"apiVersion": "v1", "kind": "ConfigMap", "metadata": {"name": "gate-conf", "namespace": "net5"},
                          "data": {"default.conf": conf}})
            gate = api.deploy("net5", "gatekeeper", {"image": "nginx:1.27-alpine",
                                                     "volumeMounts": [{"name": "conf", "mountPath": "/etc/nginx/conf.d"}]})
            gate["spec"]["template"]["spec"]["volumes"] = [{"name": "conf", "configMap": {"name": "gate-conf"}}]
            items += [gate, {"apiVersion": "v1", "kind": "Service", "metadata": {"name": "gatekeeper", "namespace": "net5"},
                             "spec": {"selector": {"app": "gatekeeper"}, "ports": [{"port": 80}]}}]
            kc("apply", "-f", "-", stdin=json.dumps({"apiVersion": "v1", "kind": "List", "items": items}))
            w["answers"]["5"] = api.h(real5)

            # 2 + 3. certificates
            for room in ("2-cert-check", "3-key-match"):
                (d / room).mkdir(parents=True)
            sans = [("pay.shellventure.local", "DNS:www.shellventure.local"), ("pay.shellventure.local", "DNS:api.shellventure.local,DNS:pay.escape.lan"),
                    ("gateway", "DNS:gateway.shellventure.local,DNS:pay.shellventure.local"), ("pay", "DNS:pay.escape.com"),
                    ("pay.shellventure.local", "IP:10.0.0.7"), ("edge", "DNS:edge.shellventure.local")]
            files = [f"cert-{chr(97 + i)}.pem" for i in range(len(sans))]
            order = list(range(len(sans)))
            random.shuffle(order)
            r2 = d / "2-cert-check"
            for f, i in zip(files, order):
                cn, san = sans[i]
                ossl("req", "-x509", "-newkey", "ec", "-pkeyopt", "ec_paramgen_curve:prime256v1", "-nodes", "-days", "30",
                     "-keyout", f"/dev/null", "-out", f, "-subj", f"/CN={cn}", "-addext", f"subjectAltName={san}", cwd=r2)
                if i == 2:
                    w["answers"]["2"] = api.h(f)
            r3 = d / "3-key-match"
            match = random.choice(files)
            for f in files:
                ossl("req", "-x509", "-newkey", "ec", "-pkeyopt", "ec_paramgen_curve:prime256v1", "-nodes", "-days", "30",
                     "-keyout", "key.pem" if f == match else f"/dev/null", "-out", f, "-subj", "/CN=pay.shellventure.local", cwd=r3)
            w["answers"]["3"] = api.h(match)

    def dns_check(d, w, ans):
        ok = (ans or "").strip().lower().rstrip(".") in ("vault.secrets", "vault.secrets.svc", "vault.secrets.svc.cluster.local")
        if not ok:
            return False, "That name does not reach vault from net1."
        return True, ""

    NET = {"title": "It's Always DNS", "needs": ["kind", "docker", "kubectl", "openssl"], "dir": "network", "setup": net_setup, "kind": True, "rooms": [
        {"name": "Lost in DNS", "check": dns_check, "typed": True,
         "story": "From pod [bold]client[/] (ns net1): `wget -qO- vault` says bad address. But vault is running.",
         "task": "Find a hostname that reaches the vault Service [bold]from net1[/].\n"
                 "Test it: kubectl exec -n net1 deploy/client -- wget -qO- <name>\nThen: [cyan]check <name>[/]",
         "hints": ["Where does the vault Service live? `kubectl get svc -A | grep vault`",
                   "A short name only works inside the same namespace.", "Use <service>.<namespace>"]},
        {"name": "The Cert Check", "dir": "2-cert-check", "answer": True,
         "story": "6 certificates. Four say [bold]CN=pay.shellventure.local[/]. Browsers ignore CN.",
         "task": "Which file is really valid for host [bold]pay.shellventure.local[/]?\nThen: [cyan]check <file>[/]",
         "hints": ["Modern clients only trust the Subject Alternative Name (SAN).",
                   "`openssl x509 -in cert-a.pem -noout -ext subjectAltName`",
                   "`for f in cert-*.pem; do echo $f; openssl x509 -in $f -noout -ext subjectAltName; done`"]},
        {"name": "The Key Match", "dir": "3-key-match", "answer": True,
         "story": "A TLS secret fails with [bold]key values mismatch[/]. One cert belongs to key.pem.",
         "task": "Which cert file matches [bold]key.pem[/]? Then: [cyan]check <file>[/]",
         "hints": ["A cert and its key share the same public key.",
                   "`openssl pkey -in key.pem -pubout` vs `openssl x509 -in cert-a.pem -noout -pubkey`",
                   "`for f in cert-*.pem; do openssl x509 -in $f -noout -pubkey | cmp -s - <(openssl pkey -in key.pem -pubout) && echo $f; done`"]},
        {"name": "The Radio", "answer": True,
         "story": "Pod [bold]radio[/] (ns net4) talks on a secret port. No Service. No containerPort.",
         "task": "Find the port, forward it to your laptop, and read the page.\nThen: [cyan]check <code>[/]",
         "hints": ["Ask the pod what it listens on: `kubectl exec -n net4 deploy/radio -- netstat -tln`",
                   "`kubectl port-forward -n net4 deploy/radio 9000:<port>` (in another tab)",
                   "`curl -s localhost:9000/`"]},
        {"name": "The Gatekeeper", "answer": True,
         "story": "Service [bold]gatekeeper[/] (ns net5) answers everyone with 'wrong door'.",
         "task": "Get the code from [bold]vault.shellventure.local[/] behind it. It hides in a header.\nThen: [cyan]check <code>[/]",
         "hints": ["`kubectl port-forward -n net5 svc/gatekeeper 9001:80`",
                   "nginx picks a server by the Host header.",
                   "`curl -si -H 'Host: vault.shellventure.local' localhost:9001/ | grep -i x-escape`"]},
    ]}
    return {"sql": SQL, "network": NET}
